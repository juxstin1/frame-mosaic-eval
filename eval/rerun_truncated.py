"""Re-ask calls whose answer was cut off by the answer cap, with a larger cap. Same frames, layout and prompt.

python -m eval.rerun_truncated results/position_n16_snake_gemma4_default.jsonl --max-tokens 256 --dry-run
Writes results/<source>_cap<max-tokens>.jsonl; each record carries "rerun_of" (source file + seq_index).
"""
import argparse
import json
import sys
import time
from pathlib import Path

from gen.common import FRAME_SIZE, rng_for
from mosaic.builder import Condition

from .position_run import TARGET_KW
from .run import call_and_record, server_info


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source", type=Path)
    ap.add_argument("--max-tokens", type=int, default=256)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    src = [json.loads(line) for line in a.source.open(encoding="utf-8")]
    todo = [r for r in src if r.get("finish_reason") == "length"]
    out = a.source.with_name(f"{a.source.stem}_cap{a.max_tokens}.jsonl")
    print(f"{len(todo)} calls planned -> {out}")
    if a.dry_run or not todo:
        return
    if any(r.get("design") != "controlled_position" for r in todo):
        sys.exit("only controlled-position records can be regenerated by this script")
    srv = server_info()
    t0 = time.time()
    with out.open("a", encoding="utf-8") as fh:
        for r in todo:
            kw, fn = TARGET_KW[r["task"]]
            frames, answer, _ = fn(r["n"], rng_for(r["task"], r["n"], r["seq_index"], r["base_seed"]), FRAME_SIZE,
                                   **{kw: r["target_position"]})
            assert answer[{"tile_probe": "probe_frame", "moving_dot": "change_frame"}[r["task"]]] == r["truth"]
            cond = Condition(**r["condition"])
            rec = call_and_record(srv, "gemma4uv", r["task"], frames, answer, cond,
                                  {"run_id": r["run_id"], "seq_index": r["seq_index"], "base_seed": r["base_seed"],
                                   "target_position": r["target_position"], "design": "controlled_position",
                                   "rerun_of": {"file": a.source.name, "seq_index": r["seq_index"]}},
                                  max_tokens=a.max_tokens)
            fh.write(json.dumps(rec) + "\n")
            fh.flush()
    print(f"done in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
